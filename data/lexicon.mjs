export function flatAttributes() {
  const out = [];
  let vec = 0, struct = 0, sort = 0;
  for (const c of CATEGORIES) {
    for (const [key, label, synonyms = []] of c.attributes) {
      const inFlavor = ['aroma', 'texture', 'style'].includes(c.kind);
      out.push({
        key, label, synonyms,
        category: c.key, group: c.group, kind: c.kind,
        vec_index: inFlavor ? ++vec : null,
        struct_index: c.kind === 'structure' ? ++struct : null,
        sort: ++sort,
      });
    }
  }
  return out;
}
