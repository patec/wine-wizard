// Builds SQL seed files from data/lexicon.mjs and data/wines/*.json
// usage: node scripts/build-seed.mjs   → supabase/seed/*.sql
import fs from 'node:fs';
import path from 'node:path';
import { CATEGORIES, GROUPS, SCALE_LABELS, flatAttributes } from '../data/lexicon.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const outDir = path.join(root, 'supabase', 'seed');
fs.mkdirSync(outDir, { recursive: true });

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;

// ── lexicon ──
const groups = Object.fromEntries(GROUPS.map((g) => [g.key, g]));
const attrs = flatAttributes();
let sql = '-- generated by scripts/build-seed.mjs — lexicon\n';
sql += 'insert into public.attribute_categories(key,label,group_key,group_label,group_order,kind,weight,description,sort) values\n';
sql += CATEGORIES.map((c, i) => `(${q(c.key)},${q(c.label)},${q(c.group)},${q(groups[c.group].label)},${groups[c.group].order},${q(c.kind)},${c.weight},${q(c.description)},${i + 1})`).join(',\n');
sql += '\non conflict (key) do update set label=excluded.label, group_key=excluded.group_key, group_label=excluded.group_label, group_order=excluded.group_order, kind=excluded.kind, weight=excluded.weight, description=excluded.description, sort=excluded.sort;\n\n';
sql += 'insert into public.attributes(id,key,label,category,kind,synonyms,vec_index,struct_index,scale_labels,sort) values\n';
sql += attrs.map((a) => `(${a.sort},${q(a.key)},${q(a.label)},${q(a.category)},${q(a.kind)},${arr(a.synonyms)},${a.vec_index ?? 'null'},${a.struct_index ?? 'null'},${SCALE_LABELS[a.key] ? arr(SCALE_LABELS[a.key]) : 'null'},${a.sort})`).join(',\n');
sql += '\non conflict (id) do update set key=excluded.key, label=excluded.label, category=excluded.category, kind=excluded.kind, synonyms=excluded.synonyms, vec_index=excluded.vec_index, struct_index=excluded.struct_index, scale_labels=excluded.scale_labels, sort=excluded.sort;\n';
fs.writeFileSync(path.join(outDir, '01_lexicon.sql'), sql);

// ── wines (compact) ──
const id = new Map(attrs.map((a) => [a.key, a.sort]));
const files = fs.readdirSync(path.join(root, 'data', 'wines')).filter((f) => f.endsWith('.json')).sort();
const wines = files.flatMap((f) => JSON.parse(fs.readFileSync(path.join(root, 'data', 'wines', f), 'utf8')));
const compact = wines.map((w) => {
  const x = [
    ...Object.entries(w.structure).map(([k, v]) => `${id.get(k)}:${Math.round(v * 100)}`),
    ...Object.entries(w.notes).map(([k, v]) => `${id.get(k)}:${Math.max(1, Math.round(v * 100))}`),
    ...w.pairings.map((k) => `${id.get(k)}:100`),
  ].join(',');
  return { s: w.slug, n: w.name, p: w.producer, t: w.type, c: w.country, r: w.region, a: w.appellation ?? null, g: w.grapes,
    pr: w.price, abv: w.abv, e: w.elevage ?? null, sv: w.serve ?? null, d: w.decant ?? null, w: w.window ?? null, ds: w.description, x };
});
const CHUNK = 30;
for (let i = 0; i < compact.length; i += CHUNK) {
  const body = JSON.stringify(compact.slice(i, i + CHUNK)).replace(/'/g, "''");
  fs.writeFileSync(path.join(outDir, `02_wines_${String(i / CHUNK + 1).padStart(2, '0')}.sql`),
    `-- generated by scripts/build-seed.mjs\nselect public.seed_wines('${body}'::jsonb);\n`);
}
console.log(`lexicon: ${CATEGORIES.length} categories, ${attrs.length} attributes; wines: ${wines.length} in ${Math.ceil(compact.length / CHUNK)} files`);
